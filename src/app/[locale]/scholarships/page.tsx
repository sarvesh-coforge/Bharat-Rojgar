import React from 'react';
import { getNotificationsByCategory } from '@/services/notification.service';
import { CategoryListingView } from '@/components/notifications/CategoryListingView';
import { setRequestLocale } from 'next-intl/server';
import { Metadata } from 'next';

export const metadata: Metadata = {
  title: 'Scholarship Schemes 2026 | National & State Portals | Bharat Rojgar',
  description: 'Apply online for Central Sector, Pre-Matric, Post-Matric, UP Scholarship, NSP portal schemes and financial aid.',
};

export default async function ScholarshipsPage({
  params,
  searchParams,
}: {
  params: Promise<{ locale: string }>;
  searchParams: Promise<{ org?: string; search?: string; page?: string }>;
}) {
  const { locale } = await params;
  const sParams = await searchParams;
  setRequestLocale(locale);

  const currentPage = sParams.page ? parseInt(sParams.page, 10) : 1;
  const { items, total, totalPages } = await getNotificationsByCategory('scholarships', {
    organization: sParams.org,
    search: sParams.search,
    page: currentPage,
    limit: 15,
  });

  return (
    <CategoryListingView
      categoryName="Government Scholarship Schemes"
      categoryNameHi="छात्रवृत्ति योजनाएं (Scholarships 2026)"
      categorySlug="scholarships"
      description="Central and state government scholarship eligibility, deadlines and official portals"
      items={items}
      total={total}
      currentPage={currentPage}
      totalPages={totalPages}
      selectedOrg={sParams.org}
      searchQuery={sParams.search}
      locale={locale}
    />
  );
}
